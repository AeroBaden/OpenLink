export const dictionaries: Record<Lang, Dict> = { en, de };

export function translate(lang: Lang, key: string): string {
  return dictionaries[lang]?.[key] ?? en[key] ?? key;
}

/** Pick the German label when the UI language is German and one exists. */
export function label(lang: Lang, base: string, deLabel?: string): string {
  return lang === 'de' && deLabel ? deLabel : base;
}
